typedef struct _statclass_signal2mel {
  SCFLOAT* signal;
  SCFLOAT* w;
  SCFLOAT* t;

  float* tTmp;

  SCFLOAT* mel;
  HANDLE_IIS_FFT hIisFft;

} STATCLASS_SIGNAL2MEL;

static void signal2mel(HANDLE_STATCLASS_SIGNAL2MEL hSignal2Mel,
                       SCFLOAT* x,
                       SCFLOAT* memXIn,
                       const float* mfccFiltWeights,
                       int Nlength_mfccFilterWeights,
                       int Mlength_mfccFilterWeights,
                       SCFLOAT* mel) {
  int i, j;

  SCFLOAT* signal = NULL;
  SCFLOAT* w = NULL;
  SCFLOAT* t = NULL;
  SCFLOAT tmpSum;
  float* tTmp = NULL;

  signal = hSignal2Mel->signal;
  w = hSignal2Mel->w;
  t = hSignal2Mel->t;
  tTmp = hSignal2Mel->tTmp;

  memcpy(signal, memXIn, L_PAST * sizeof(SCFLOAT));
  memcpy(&signal[L_PAST], x, (L_FRAME + L_NEXT) * sizeof(SCFLOAT));

  for (i = 0; i < L_ANALYSIS; i++) {
    t[i] = signal[i] * w[i];
  }

  for (i = 0; i < L_ANALYSIS; i++) {
    tTmp[i] = (float)t[i];
  }

  IIS_FFT_Apply_RFFT(hSignal2Mel->hIisFft, tTmp, tTmp);

  for (i = 1; i < L_ANALYSIS / 2; i++) {
    t[i] = tTmp[i * 2] * tTmp[i * 2] + tTmp[i * 2 + 1] * tTmp[i * 2 + 1];
  }

  t[0] = tTmp[0] * tTmp[0];
  t[L_ANALYSIS / 2] = tTmp[1] * tTmp[1];

  for (j = 0; j < Nlength_mfccFilterWeights; j++) {
    tmpSum = 0;
    for (i = 0; i < Mlength_mfccFilterWeights; i++) {
      tmpSum += (SCFLOAT)*mfccFiltWeights * t[i];
      mfccFiltWeights++;
    }
    mel[j] = tmpSum;
  }

  return;
}

STATCLASS_ERROR_CODE STATCLASS_Signal2Mel_Open(HANDLE_STATCLASS_SIGNAL2MEL* hSignal2Mel) {
  STATCLASS_ERROR_CODE error = STATCLASS_NO_ERROR;

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == hSignal2Mel) {
      error = STATCLASS_INVALID_POINTER;
    } else {
      if (NULL == (*hSignal2Mel = (STATCLASS_SIGNAL2MEL*)iisCalloc(1, sizeof(STATCLASS_SIGNAL2MEL)))) {
        error = STATCLASS_MEMORY_ALLOC_ERROR;
      }
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == ((*hSignal2Mel)->signal = (SCFLOAT*)iisCalloc(L_ANALYSIS, sizeof(SCFLOAT)))) {
      error = STATCLASS_MEMORY_ALLOC_ERROR;
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == ((*hSignal2Mel)->w = (SCFLOAT*)iisCalloc(L_ANALYSIS, sizeof(SCFLOAT)))) {
      error = STATCLASS_MEMORY_ALLOC_ERROR;
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    int i;

    for (i = 0; i < L1; i++) {
      (*hSignal2Mel)->w[i] = (SCFLOAT)(0.54 - 0.46 * cos(2 * PI * i / (2 * L1 - 1)));
    }

    for (; i < L_ANALYSIS; i++) {
      (*hSignal2Mel)->w[i] = (SCFLOAT)cos(2 * PI * (i - L1) / (4 * L2 - 1));
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == ((*hSignal2Mel)->t = (SCFLOAT*)iisCalloc(L_ANALYSIS, sizeof(SCFLOAT)))) {
      error = STATCLASS_MEMORY_ALLOC_ERROR;
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == ((*hSignal2Mel)->tTmp = (float*)iisCalloc(L_ANALYSIS, sizeof(float)))) {
      error = STATCLASS_MEMORY_ALLOC_ERROR;
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == ((*hSignal2Mel)->mel = (SCFLOAT*)iisCalloc(MEL_SIZE, sizeof(SCFLOAT)))) {
      error = STATCLASS_MEMORY_ALLOC_ERROR;
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    IIS_FFT_ERROR err;
    err = IIS_RFFT_Create(&((*hSignal2Mel)->hIisFft), L_ANALYSIS, -1);

    if (err != IIS_FFT_NO_ERROR) {
      error = STATCLASS_MEMORY_ALLOC_ERROR;
    }
  }

  return error;
}

STATCLASS_ERROR_CODE STATCLASS_Signal2Mel_Advance(HANDLE_STATCLASS_SIGNAL2MEL hSignal2Mel,
                                                  SCFLOAT* pSignal,
                                                  SCFLOAT* pOldSignal,
                                                  SCFLOAT* pMel) {
  STATCLASS_ERROR_CODE error = STATCLASS_NO_ERROR;
  int i;

  if (STATCLASS_NO_ERROR == error) {
    for (i = 0; i < MEL_SIZE; i++) {
      hSignal2Mel->mel[i] = pMel[i];
    }

    signal2mel(hSignal2Mel,
               pSignal,
               pOldSignal,
               mfccFilterWeights,
               MFCC_SIZE_N,
               MFCC_SIZE_M,
               hSignal2Mel->mel);

    for (i = 0; i < MEL_SIZE; i++) {
      pMel[i] = (SCFLOAT)hSignal2Mel->mel[i];
    }
  }
  return error;
}

STATCLASS_ERROR_CODE STATCLASS_Signal2Mel_Close(HANDLE_STATCLASS_SIGNAL2MEL* hSignal2Mel) {
  STATCLASS_ERROR_CODE error = STATCLASS_NO_ERROR;

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == (*hSignal2Mel)->signal) {
      error = STATCLASS_INVALID_POINTER;
    } else {
      iisFree((*hSignal2Mel)->signal);
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == (*hSignal2Mel)->t) {
      error = STATCLASS_INVALID_POINTER;
    } else {
      iisFree((*hSignal2Mel)->t);
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == (*hSignal2Mel)->w) {
      error = STATCLASS_INVALID_POINTER;
    } else {
      iisFree((*hSignal2Mel)->w);
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == (*hSignal2Mel)->tTmp) {
      error = STATCLASS_INVALID_POINTER;
    } else {
      iisFree((*hSignal2Mel)->tTmp);
    }
  }

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == (*hSignal2Mel)->mel) {
      error = STATCLASS_INVALID_POINTER;
    } else {
      iisFree((*hSignal2Mel)->mel);
    }
  }

  if ((*hSignal2Mel)->hIisFft)
    IIS_RFFT_Destroy(&((*hSignal2Mel)->hIisFft));

  if (STATCLASS_NO_ERROR == error) {
    if (NULL == *hSignal2Mel) {
      error = STATCLASS_INVALID_POINTER;
    } else {
      iisFree(*hSignal2Mel);
    }
  }

  return error;
}
