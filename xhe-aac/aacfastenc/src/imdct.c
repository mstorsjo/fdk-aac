static void Dct_iv(float vec[], int size, HANDLE_IIS_FFT hFft) {
  int i;
  const double *sin_cos_tab = NULL;

  float vecRe[512] = {0};
  float vecIm[512] = {0};

  if (size == 1024)
    sin_cos_tab = sin_cos_tab_1024;
  else if (size == 128)
    sin_cos_tab = sin_cos_tab_128;
  else if (size == 768)
    sin_cos_tab = sin_cos_tab_768;
  else if (size == 96)
    sin_cos_tab = sin_cos_tab_96;
  else
    assert(0);

  assert(NULL != sin_cos_tab);

  for (i = 0; i < size / 4; i++) {
    double sinPhi, cosPhi, t1, t2, t3, t4;

    sinPhi = sin_cos_tab[2 * i];
    cosPhi = sin_cos_tab[2 * i + 1];

    t1 = -vec[i * 2] * cosPhi - vec[size - 1 - i * 2] * sinPhi;
    t2 = vec[size - 1 - i * 2] * (float)cosPhi - vec[i * 2] * (float)sinPhi;

    sinPhi = sin_cos_tab[size - 2 - 2 * i];
    cosPhi = sin_cos_tab[size - 1 - 2 * i];

    t3 = -vec[size - 2 - i * 2] * cosPhi - vec[i * 2 + 1] * sinPhi;
    t4 = vec[i * 2 + 1] * (float)cosPhi - vec[size - 2 - i * 2] * (float)sinPhi;

    vec[i * 2] = (float)t1;
    vec[i * 2 + 1] = (float)t2;

    vec[size - 2 - i * 2] = (float)t3;
    vec[size - 1 - i * 2] = (float)t4;
  }

  for (i = 0; i < size / 2; i++) {
    vecRe[i] = vec[2 * i];
    vecIm[i] = vec[2 * i + 1];
  }

  IIS_FFT_Apply_CFFT(hFft, vecRe, vecIm, vecRe, vecIm);

  for (i = 0; i < size / 2; i++) {
    vec[2 * i] = vecRe[i];
    vec[2 * i + 1] = vecIm[i];
  }

  for (i = 0; i < size / 4; i++) {
    double sinPhi, cosPhi, t1, t2, t3, t4;

    sinPhi = sin_cos_tab[2 * i];
    cosPhi = sin_cos_tab[2 * i + 1];

    t1 = vec[i * 2] * cosPhi - vec[i * 2 + 1] * sinPhi;
    t2 = vec[i * 2 + 1] * (float)cosPhi + vec[i * 2] * (float)sinPhi;

    sinPhi = sin_cos_tab[size - 2 - 2 * i];
    cosPhi = sin_cos_tab[size - 1 - 2 * i];

    t3 = vec[size - 2 - i * 2] * cosPhi - vec[size - 1 - i * 2] * sinPhi;
    t4 = vec[size - 1 - i * 2] * (float)cosPhi + vec[size - 2 - i * 2] * (float)sinPhi;

    vec[i * 2] = (float)-t1;
    vec[i * 2 + 1] = (float)-t4;
    vec[size - 2 - i * 2] = (float)-t3;
    vec[size - 1 - i * 2] = (float)-t2;
  }
}

static void imdct(float *p_in_data, float *p_out_data, int windowLen, HANDLE_IIS_FFT hFft) {
  float tmpBuffer[FRAME_LEN_LONG];

  const int N = windowLen;

  int i;

  for (i = 0; i < N / 2; i++) {
    tmpBuffer[i] = (p_in_data[i] * (2.0F / N));
  }

  Dct_iv(tmpBuffer, N / 2, hFft);

  for (i = 0; i < N / 4; i++) {
    p_out_data[i] = tmpBuffer[N / 4 + i];
    p_out_data[N / 2 - i - 1] = -tmpBuffer[N / 4 + i];
    p_out_data[N / 2 + N / 4 + i] = -tmpBuffer[i];
    p_out_data[N / 2 + N / 4 - i - 1] = -tmpBuffer[i];
  }
}

static void WindowData(int block_type, int granule_length, float *pdataToWindow) {
  int i;

  float const *LongWindowKBD = NULL;
  float const *ShortWindowSine = NULL;

  const int frame_length_long = granule_length;
  const int frame_length_short = granule_length / TRANS_FAC;
  const int ls_trans = (frame_length_long - frame_length_short) / 2;

  switch (granule_length) {
    case 1024:

      LongWindowKBD = LongWindowKBD1024;
      ShortWindowSine = ShortWindowSine128;

      break;
    case 768:

      LongWindowKBD = LongWindowKBD768;
      ShortWindowSine = ShortWindowSine96;

      break;
    default:
      assert(0);
      break;
  }

  switch (block_type) {
    case LONG_WINDOW:
      for (i = 0; i < frame_length_long / 2; i++) {
        pdataToWindow[i] *= LongWindowKBD[i];
        pdataToWindow[frame_length_long - i - 1] *= LongWindowKBD[frame_length_long - i - 1];

        pdataToWindow[(frame_length_long + i)] *= LongWindowKBD[frame_length_long - i - 1];
        pdataToWindow[(frame_length_long * 2 - i - 1)] *= LongWindowKBD[i];
      }

      break;

    case START_WINDOW:
      for (i = 0; i < frame_length_long / 2; i++) {
        pdataToWindow[i] *= LongWindowKBD[i];
        pdataToWindow[frame_length_long - i - 1] *= LongWindowKBD[frame_length_long - i - 1];
      }
      for (i = 0; i < ls_trans; i++) {
        pdataToWindow[2 * frame_length_long - i - 1] = 0.0;
      }
      for (i = 0; i < frame_length_short / 2; i++) {
        pdataToWindow[frame_length_long + i + ls_trans] *= ShortWindowSine[frame_length_short - i - 1];
        pdataToWindow[frame_length_long * 2 - i - 1 - ls_trans] *= ShortWindowSine[i];
      }
      break;

    case STOP_WINDOW:
      for (i = 0; i < frame_length_short / 2; i++) {
        pdataToWindow[i + ls_trans] *= ShortWindowSine[i];
        pdataToWindow[frame_length_long - ls_trans - i - 1] *= ShortWindowSine[frame_length_short - i - 1];
      }
      for (i = 0; i < ls_trans; i++) {
        pdataToWindow[i] = 0.0;
      }
      for (i = 0; i < frame_length_long / 2; i++) {
        pdataToWindow[frame_length_long + i] *= LongWindowKBD[frame_length_long - i - 1];
        pdataToWindow[frame_length_long * 2 - i - 1] *= LongWindowKBD[i];
      }

      break;

    case SHORT_WINDOW:
      for (i = 0; i < frame_length_short / 2; i++) {
        pdataToWindow[i] *= ShortWindowSine[i];
        pdataToWindow[frame_length_short - i - 1] *= ShortWindowSine[frame_length_short - i - 1];

        pdataToWindow[frame_length_short + i] *= ShortWindowSine[frame_length_short - i - 1];
        pdataToWindow[frame_length_short * 2 - i - 1] *= ShortWindowSine[i];
      }
      break;

    default:
      assert(0);
      break;
  }
}

void iisaacfenc_IMDCT_noOA(
    float p_in_data[],
    float p_out_data[],
    int block_type,
    int nlong,
    int nshort,
    int num_short_win,
    int feed_shortblock_spec,
    struct T_IIS_FFT *hFft) {
  int k;
  float *fp;

  int nflat_ls = (nlong - nshort) / 2;
  setFLOAT(0.0f, p_out_data, 2 * (nlong));

  switch (block_type) {
    case LONG_WINDOW:
    case START_WINDOW:
    case STOP_WINDOW:
    case STOPSTART_WINDOW:
      imdct(p_in_data, p_out_data, 2 * nlong, hFft);
      break;
    case SHORT_WINDOW:
      fp = p_out_data + nflat_ls;
      for (k = num_short_win - 1; k-- >= 0;) {
        float transf_buf[2 * FRAME_LEN_LONG / TRANS_FAC];
        imdct(p_in_data, transf_buf, 2 * nshort, hFft);
        WindowData(block_type, nlong, transf_buf);
        addFLOAT(transf_buf, fp, fp, 2 * nshort);

        p_in_data += feed_shortblock_spec;
        fp += nshort;
      }
      break;

    default:
      break;
  }
}
